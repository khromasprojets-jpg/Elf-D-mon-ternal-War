// ─── FORMAT PAQUET ────────────────────────────────────────────────────────────
// Entête: [4 bytes MAGIC][4 bytes payload_length]
// Payload: [8 bytes double timestamp][4 bytes dest][4 bytes cmd][JSON data]
const MAGIC = 0xDEADBEEF;

function parsePacket(buf) {
  if (buf.length < 8) return null;
  const magic = buf.readUInt32BE(0);
  const plen  = buf.readUInt32BE(4);
  if (buf.length < 8 + plen) return null;
  const payload  = buf.slice(8, 8 + plen);
  return { magic, payload, consumed: 8 + plen };
}

function parsePayload(payload) {
  try {
    if (payload.length < 16) return null;
    const timestamp = payload.readDoubleBE(0);   // 8 bytes
    const dest      = payload.readInt32BE(8);     // 4 bytes
    const cmd       = payload.readInt32BE(12);    // 4 bytes
    let   data      = {};
    if (payload.length > 16) {
      const jsonStr = payload.slice(16).toString('utf8').replace(/\0/g, '').trim();
      if (jsonStr.startsWith('{')) data = JSON.parse(jsonStr);
    }
    return { timestamp, dest, cmd, data };
  } catch(e) {
    return null;
  }
}

function buildPacket(dest, cmd, data = {}) {
  const jsonBuf  = Buffer.from(JSON.stringify(data), 'utf8');
  const payLen   = 16 + jsonBuf.length;
  const buf      = Buffer.alloc(8 + payLen);
  buf.writeUInt32BE(MAGIC, 0);
  buf.writeUInt32BE(payLen, 4);
  buf.writeDoubleBE(Date.now() / 1000, 8);
  buf.writeInt32BE(dest, 16);
  buf.writeInt32BE(cmd, 20);
  jsonBuf.copy(buf, 24);
  return buf;
}

function sendTo(player, dest, cmd, data = {}) {
  try { player.socket.write(buildPacket(dest, cmd, data)); }
  catch(e) { /* socket fermée */ }
}

function broadcast(dest, cmd, data = {}, excludeId = null) {
  const pkt = buildPacket(dest, cmd, data);
  players.forEach((p, id) => {
    if (id !== excludeId) try { p.socket.write(pkt); } catch(e) {}
  });
}

function broadcastScene(sceneId, dest, cmd, data = {}, excludeId = null) {
  const set = scenes.get(sceneId);
  if (!set) return;
  const pkt = buildPacket(dest, cmd, data);
  set.forEach(id => {
    if (id === excludeId) return;
    const p = players.get(id);
    if (p) try { p.socket.write(pkt); } catch(e) {}
  });
}

