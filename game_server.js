async function routePacket(player, dest, cmd, data) {
  const handler = handlers[dest];
  if (!handler) {
    console.log(`[ROUTE] dest=${dest} cmd=${cmd} — pas de handler`);
    return;
  }
  try {
    const result = await handler(player, cmd, data);
    if (result) sendTo(player, dest, cmd, result);
  } catch(err) {
    console.error(`[ERREUR] dest=${dest} cmd=${cmd}:`, err.message);
    sendTo(player, dest, cmd, { ok: false, error: err.message });
  }
}

