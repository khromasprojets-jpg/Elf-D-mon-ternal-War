// ── Scene ─────────────────────────────────────────────────────────────────────
async function handleScene(player, cmd, data) {
  switch (cmd) {

    case OPCODES.SceneCmd.ENTER_SCENE: {
      const sceneId = data.sceneId || 'village';
      player.sceneId = sceneId;
      player.x = data.x || 0;
      player.y = data.y || 0;
      if (!scenes.has(sceneId)) scenes.set(sceneId, new Set());
      scenes.get(sceneId).add(player.id);
      // Notifier les autres
      broadcastScene(sceneId, DEST.SCENE, OPCODES.SceneCmd.PUSH_ENTER_SENCE, {
        playerId: player.id, nom: player.perso?.nom, classeEmoji: player.perso?.classe_emoji,
        x: player.x, y: player.y,
      }, player.id);
      // Envoyer la liste des joueurs présents
      const present = [];
      scenes.get(sceneId).forEach(id => {
        const p = players.get(id);
        if (p && p.id !== player.id) present.push({ id: p.id, nom: p.perso?.nom, x: p.x, y: p.y });
      });
      return { ok: true, sceneId, players: present };
    }

    case OPCODES.SceneCmd.LEFT_SCENE: {
      if (player.sceneId) {
        const set = scenes.get(player.sceneId);
        if (set) set.delete(player.id);
        broadcastScene(player.sceneId, DEST.SCENE, OPCODES.SceneCmd.PUSH_LEFT_SENCE, {
          playerId: player.id,
        });
        player.sceneId = null;
      }
      return { ok: true };
    }

    case OPCODES.SceneCmd.MOVE: {
      player.x = data.x;
      player.y = data.y;
      broadcastScene(player.sceneId, DEST.SCENE, OPCODES.SceneCmd.PUSH_MOVE, {
        playerId: player.id, x: data.x, y: data.y,
      }, player.id);
      return null; // pas de réponse au sender
    }

    case OPCODES.SceneCmd.SWITCH_CITY:
      return { ok: true, cityId: data.cityId };

    default:
      return null;
  }
}

